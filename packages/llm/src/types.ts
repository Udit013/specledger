import { candidateSchema, equipmentClassSchema, fieldDefinitionSchema } from '@specledger/core';
import type { Result } from '@specledger/core';
import { z } from 'zod';

import type { LlmError } from './errors.js';

export const pageTextSchema = z.strictObject({
  pageNumber: z.number().int().min(1),
  text: z.string(),
});
export type PageText = z.infer<typeof pageTextSchema>;

// Everything a provider needs, and everything the replay key covers.
export const extractionRequestSchema = z
  .strictObject({
    equipmentClass: equipmentClassSchema,
    fields: z.array(fieldDefinitionSchema).min(1),
    pages: z.array(pageTextSchema).min(1),
    promptVersion: z.string().min(1),
    // True only for documents generated by the synthetic corpus. Gemini's free tier and the
    // recorder refuse anything else, because free-tier content may be used to improve Google's
    // products.
    synthetic: z.boolean(),
  })
  .refine((request) => new Set(request.fields.map((f) => f.name)).size === request.fields.length, {
    message: 'field names must be unique',
    path: ['fields'],
  })
  .refine(
    (request) => new Set(request.pages.map((p) => p.pageNumber)).size === request.pages.length,
    { message: 'page numbers must be unique', path: ['pages'] },
  );
export type ExtractionRequest = z.infer<typeof extractionRequestSchema>;

export const tokenUsageSchema = z.strictObject({
  inputTokens: z.number().int().nonnegative().nullable(),
  outputTokens: z.number().int().nonnegative().nullable(),
});
export type TokenUsage = z.infer<typeof tokenUsageSchema>;

// Candidates are schema-valid model output and nothing more: whether a quote is on its page, or a
// number is inside its quote, is checked later by the verifier (Phase 5).
export const extractionResponseSchema = z.strictObject({
  modelId: z.string().min(1),
  promptVersion: z.string().min(1),
  candidates: z.array(candidateSchema),
  usage: tokenUsageSchema,
});
export type ExtractionResponse = z.infer<typeof extractionResponseSchema>;

// What the model itself must return for one prompt, with field names limited to those requested.
export function modelOutputSchema(fieldNames: readonly string[]) {
  const [first, ...rest] = fieldNames;
  if (first === undefined) throw new Error('modelOutputSchema needs at least one field name');
  return z.strictObject({
    candidates: z.array(candidateSchema.extend({ fieldName: z.enum([first, ...rest]) })),
  });
}

export interface ExtractOptions {
  readonly signal?: AbortSignal;
  readonly timeoutMs: number;
  // Correlates log lines; generated when absent.
  readonly requestId?: string;
}

// The model is an untrusted component: implementations return schema-valid data or a typed error,
// and nothing they return is trusted further than that.
export interface LlmProvider {
  readonly name: string;
  readonly modelId: string;
  extract(
    request: ExtractionRequest,
    options: ExtractOptions,
  ): Promise<Result<ExtractionResponse, LlmError>>;
}
